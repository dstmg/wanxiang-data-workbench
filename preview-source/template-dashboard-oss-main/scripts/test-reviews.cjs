const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const vm = require('node:vm');
const ts = require('typescript');
async function main() {
  const source = await fs.readFile(path.join(__dirname, '../src/lib/reviews.ts'), 'utf8');
  const compiled = ts.transpileModule(source, {compilerOptions: {module: ts.ModuleKind.CommonJS, esModuleInterop: true}}).outputText;
  const box = {exports: {}, require, process, Promise};
  vm.runInNewContext(compiled, box);
  const {readReviews, updateReviews} = box.exports;
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'wanxiang-review-test-'));
  let state = await readReviews(directory);
  async function command(body) {state = await updateReviews({...body, revision: state.revision}, directory);return state;}
  await command({op: 'createShop', name: '测试店铺A'});
  const a = state.shops[0].id;
  await command({op: 'createShop', name: '测试店铺B'});
  const b = state.shops[1].id;
  const key = 'a'.repeat(64);
  await command({op: 'bindReport', shopId: a, reportKey: key});
  await assert.rejects(command({op: 'bindReport', shopId: b, reportKey: key}), /不能改绑/);
  await command({op: 'createReview', shopId: a, title: '首轮复盘'});
  const reviewId = state.reviews[0].id;
  await assert.rejects(command({op: 'updateReview', shopId: b, reviewId, title: '错误店铺', summary: ''}), /该店铺没有/);
  const snapshot = {view: '推广计划', start: '2026-09-27', end: '2026-10-03', reportKey: key, metrics: {spend: 100, roi: 2}, objectId: '42', objectName: '测试计划'};
  await command({op: 'addIssue', shopId: a, reviewId, snapshot});
  const issueId = state.reviews[0].issues[0].id;
  await command({op: 'updateIssue', shopId: a, reviewId, issueId, problem: '低于场景ROI', action: '核查转化', status: 'done', executedAt: '2026-10-05', followupDate: '2026-10-12', outcome: '', snapshot: {...snapshot, metrics: {roi: 999}}});
  assert.equal(state.reviews[0].issues[0].snapshot.metrics.roi, 2);
  assert.equal(state.reviews[0].issues[0].status, 'done');
  await assert.rejects(command({op:'archiveReview',shopId:b,reviewId,archived:true}), /该店铺没有/);
  await command({op:'archiveIssue',shopId:a,reviewId,issueId,archived:true});
  assert.ok(state.reviews[0].issues[0].archivedAt);
  await command({op:'archiveIssue',shopId:a,reviewId,issueId,archived:false});
  assert.equal(state.reviews[0].issues[0].archivedAt,undefined);
  await command({op:'archiveReview',shopId:a,reviewId,archived:true});
  assert.ok(state.reviews[0].archivedAt);
  await command({op:'archiveReview',shopId:a,reviewId,archived:false});
  assert.equal(state.reviews[0].archivedAt,undefined);
  assert.equal(state.reviews[0].issues[0].problem,'低于场景ROI');
  const utilBox={exports:{},require};
  vm.runInNewContext(ts.transpileModule(await fs.readFile(path.join(__dirname,'../src/lib/review-utils.ts'),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,utilBox);
  const issue=state.reviews[0].issues[0];
  assert.equal(utilBox.exports.isDue(issue,'2026-10-12'),true);
  assert.equal(utilBox.exports.isDue(issue,'2026-10-11'),false);
  assert.equal(utilBox.exports.isDue({...issue,status:'verified'},'2026-10-12'),false);
  assert.equal(utilBox.exports.isDue({...issue,status:'pending'},'2026-10-12'),false);
  assert.equal(utilBox.exports.isDue({...issue,archivedAt:'2026-10-12'},'2026-10-12'),false);
  assert.equal(utilBox.exports.hasIssueContent({...issue,problem:'',action:'',outcome:'',executedAt:'',followupDate:''}),false);
  const revision = state.revision;
  const results = await Promise.allSettled([updateReviews({op: 'createShop', name: '并发1', revision}, directory), updateReviews({op: 'createShop', name: '并发2', revision}, directory)]);
  assert.equal(results.filter(x => x.status === 'fulfilled').length, 1);
  assert.equal(results.filter(x => x.status === 'rejected').length, 1);
  state = await readReviews(directory);
  assert.equal(state.revision, revision + 1);
  assert.equal(JSON.parse(await fs.readFile(path.join(directory, 'reviews.previous.json'), 'utf8')).revision, revision);
  await fs.writeFile(path.join(directory, 'reviews.json'), '{invalid');
  await assert.rejects(readReviews(directory));
  await assert.rejects(updateReviews({op: 'createShop', name: '不得覆盖', revision: 0}, directory));
  assert.equal(await fs.readFile(path.join(directory, 'reviews.json'), 'utf8'), '{invalid');
  console.log('PASS: 店铺隔离、报表绑定、证据不变、状态保存、重读、上一版备份、并发防覆盖、损坏文件保护');
  console.log('测试目录（仅测试数据）：' + directory);
}
main().catch(error => {console.error(error);process.exitCode = 1;});
